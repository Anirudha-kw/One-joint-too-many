"""Build the browser assets for the FR3 article from MuJoCo Menagerie.

Outputs
  models/fr3_torque.xml    FR3 with torque motors (ctrl = joint torque, N·m), no meshes
  models/fr3_position.xml  FR3 with Menagerie's position actuators, no meshes
  assets/fr3_meshes.bin    decimated, quantized visual meshes, one part per (link, color)
  assets/fr3_meshes.json   manifest for the .bin

The physics models drop every geom. Each FR3 link has an explicit <inertial>, so
mass properties are unchanged, and the article's figures do not use contacts.
The script checks that the mass matrix and bias forces still match the
original model.

Usage
  git clone --depth 1 https://github.com/google-deepmind/mujoco_menagerie.git /path/to/menagerie
  python tools/build_web_assets.py /path/to/menagerie/franka_fr3
"""

import json
import pathlib
import sys
import xml.etree.ElementTree as ET

import fast_simplification
import mujoco
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "franka_fr3")
KEEP_FRACTION = 0.25  # fraction of triangles kept per part

HEADER = (
    "<!-- Generated by tools/build_web_assets.py from MuJoCo Menagerie's franka_fr3/fr3.xml\n"
    "     (Apache-2.0, see assets/MENAGERIE_LICENSE). All geoms are removed: every link has an\n"
    "     explicit <inertial>, so the dynamics are unchanged, and the article does not use contacts. -->\n"
)


def strip_geometry(root):
    for parent in root.iter():
        for child in list(parent):
            if child.tag == "geom":
                parent.remove(child)
    asset = root.find("asset")
    if asset is not None:
        root.remove(asset)
    # The visual/collision default classes are now unused but harmless; drop them for clarity.
    for d in root.iter("default"):
        for child in list(d):
            if child.tag == "default" and child.get("class") in ("visual", "collision"):
                d.remove(child)
    compiler = root.find("compiler")
    compiler.attrib.pop("meshdir", None)


def to_torque(root):
    act = root.find("actuator")
    limits = {}
    for a in list(act):
        lo, hi = a.get("forcerange").split()
        limits[a.get("joint")] = hi
        act.remove(a)
    for joint, hi in limits.items():
        ET.SubElement(act, "motor", name=joint, joint=joint, ctrlrange=f"-{hi} {hi}", ctrllimited="true")
    key = root.find("keyframe/key")
    key.attrib.pop("ctrl", None)


def add_site(root):
    # Rename Menagerie's attachment_site to "flange", and add a massless "payload" body there.
    # The page sets the payload's mass at runtime (model.body_mass) to attach a load.
    for body in root.iter("body"):
        for s in body.findall("site"):
            if s.get("name") == "attachment_site":
                s.set("name", "flange")
                payload = ET.SubElement(body, "body", name="payload", pos="0 0 0.157")
                ET.SubElement(payload, "inertial", pos="0 0 0", mass="0", diaginertia="0 0 0")


def write(root, path):
    ET.indent(root, space="  ")
    path.write_text(HEADER + ET.tostring(root, encoding="unicode") + "\n")


def build_models():
    out = {}
    for kind in ("torque", "position"):
        root = ET.parse(SRC / "fr3.xml").getroot()
        strip_geometry(root)
        add_site(root)
        if kind == "torque":
            to_torque(root)
        path = ROOT / "models" / f"fr3_{kind}.xml"
        write(root, path)
        out[kind] = path
    return out


def check_models(paths):
    full = mujoco.MjModel.from_xml_path(str(SRC / "fr3.xml"))
    rng = np.random.default_rng(0)
    for kind, path in paths.items():
        lite = mujoco.MjModel.from_xml_path(str(path))
        assert lite.nq == full.nq == 7
        d1, d2 = mujoco.MjData(full), mujoco.MjData(lite)
        worst = 0.0
        for _ in range(100):
            q = rng.uniform(full.jnt_range[:, 0], full.jnt_range[:, 1])
            v = rng.uniform(-1, 1, 7)
            for m, d in ((full, d1), (lite, d2)):
                d.qpos[:] = q; d.qvel[:] = v
                mujoco.mj_forward(m, d)
            M1, M2 = np.zeros((7, 7)), np.zeros((7, 7))
            mujoco.mj_fullM(full, d1, M1); mujoco.mj_fullM(lite, d2, M2)
            worst = max(worst, np.abs(M1 - M2).max(), np.abs(d1.qfrc_bias - d2.qfrc_bias).max())
        print(f"{path.name}: max |difference| in M and bias vs. original = {worst:.1e}")
        assert worst < 1e-9


def quat_to_mat(q):
    m = np.zeros(9)
    mujoco.mju_quat2Mat(m, q)
    return m.reshape(3, 3)


def weld(v, f, tol=1e-6):
    keys = np.round(v / tol).astype(np.int64)
    _, first, inverse = np.unique(keys, axis=0, return_index=True, return_inverse=True)
    f = inverse.reshape(-1)[f]
    f = f[(f[:, 0] != f[:, 1]) & (f[:, 1] != f[:, 2]) & (f[:, 0] != f[:, 2])]
    return v[first], f


def area(v, f):
    a = v[f[:, 1]] - v[f[:, 0]]; b = v[f[:, 2]] - v[f[:, 0]]
    return 0.5 * np.linalg.norm(np.cross(a, b), axis=1).sum()


def build_meshes():
    m = mujoco.MjModel.from_xml_path(str(SRC / "fr3.xml"))
    groups = {}
    for g in range(m.ngeom):
        if m.geom_group[g] != 2 or m.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH:
            continue
        mid = m.geom_dataid[g]
        va, vn = m.mesh_vertadr[mid], m.mesh_vertnum[mid]
        fa, fn = m.mesh_faceadr[mid], m.mesh_facenum[mid]
        v = m.mesh_vert[va:va + vn].astype(np.float64)
        f = m.mesh_face[fa:fa + fn].astype(np.int64)
        # mesh frame -> body frame
        v = v @ quat_to_mat(m.geom_quat[g]).T + m.geom_pos[g]
        rgba = m.mat_rgba[m.geom_matid[g]] if m.geom_matid[g] >= 0 else m.geom_rgba[g]
        key = (m.body(m.geom_bodyid[g]).name, tuple(np.round(rgba[:3], 4)))
        gv, gf = groups.setdefault(key, ([], []))
        offset = sum(len(x) for x in gv)
        gv.append(v); gf.append(f + offset)

    parts, blobs, byte_off = [], [], 0
    tri_in = tri_out = 0
    area_tot = [0.0, 0.0]
    for (body, color), (vs, fs) in groups.items():
        v = np.concatenate(vs); f = np.concatenate(fs)
        tri_in += len(f)
        # The OBJ meshes duplicate vertices along normal/UV seams. Weld them first, or the
        # decimator sees disconnected triangles and tears holes in the surface.
        v, f = weld(v, f)
        area_in = area(v, f)
        if len(f) > 200:
            v, f = fast_simplification.simplify(v.astype(np.float32), f.astype(np.int32), target_reduction=1 - KEEP_FRACTION)
            v = v.astype(np.float64)
        tri_out += len(f)
        area_tot[0] += area_in; area_tot[1] += area(v, f)
        assert len(v) < 65536
        lo, hi = v.min(0), v.max(0)
        span = np.maximum(hi - lo, 1e-9)
        qv = np.round((v - lo) / span * 65535).astype("<u2")
        idx = f.astype("<u2")
        parts.append({
            "body": body, "color": [float(c) for c in color],
            "vertexCount": int(len(v)), "indexCount": int(idx.size),
            "positionOffset": byte_off, "indexOffset": byte_off + qv.nbytes,
            "min": lo.tolist(), "max": hi.tolist(),
        })
        blob = qv.tobytes() + idx.tobytes()
        blob += b"\0" * ((4 - len(blob) % 4) % 4)
        blobs.append(blob); byte_off += len(blob)

    (ROOT / "assets" / "fr3_meshes.bin").write_bytes(b"".join(blobs))
    (ROOT / "assets" / "fr3_meshes.json").write_text(json.dumps({"parts": parts}, indent=1))
    print(f"meshes: {len(parts)} parts, {tri_in} -> {tri_out} triangles, {byte_off / 1e6:.2f} MB, "
          f"surface area kept {100 * area_tot[1] / area_tot[0]:.1f}%")
    assert area_tot[1] > 0.95 * area_tot[0], "decimation lost too much surface"


if __name__ == "__main__":
    (ROOT / "models").mkdir(exist_ok=True)
    (ROOT / "assets").mkdir(exist_ok=True)
    paths = build_models()
    check_models(paths)
    build_meshes()
    (ROOT / "assets" / "MENAGERIE_LICENSE").write_text((SRC / "LICENSE").read_text())
